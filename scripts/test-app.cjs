const { app, BrowserWindow, dialog } = require('electron')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const assert = require('node:assert/strict')
const { pathToFileURL } = require('node:url')
const pause = ms => new Promise(resolve => setTimeout(resolve, ms))
let win
const errors = []
async function waitFor(action) {
  for (let attempt = 0; attempt < 100; attempt++) {
    const result = await action()
    if (result) return result
    await pause(100)
  }
  throw new Error('Timed out waiting for UI state')
}
async function js(code) { return win.webContents.executeJavaScript(code, true) }
let count = 0
async function check(name, action) { await action(); console.log(`PASS ${++count}: ${name}`) }
;(async () => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'videomanager-app-'))
  const originalSetPath = app.setPath.bind(app)
  app.setPath = (key, value) => originalSetPath(key, key === 'userData' ? temp : value)
  app.on('browser-window-created', (_event, created) => {
    win = created
    created.hide()
    created.webContents.setBackgroundThrottling(false)
    created.webContents.on('console-message', (_event, level, message) => { if (level >= 3) errors.push(message) })
  })
  const videos = path.join(temp, 'videos')
  await fs.mkdir(videos)
  await fs.copyFile('output/fixtures/seek #1.mp4', path.join(videos, 'seek #1.mp4'))
  await fs.copyFile('output/fixtures/seek #1.mp4', path.join(videos, 'lesson #2.mp4'))
  dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [videos] })
  await import(pathToFileURL(path.resolve('dist-electron/main.js')).href)
  await waitFor(async () => win && !win.webContents.isLoading() && await js('!!window.videosorter && !!document.querySelector("main")'))
  await check('actual preload and main IPC import local videos', async () => {
    const result = await js('window.videosorter.scanDirectory()')
    assert.equal(result.snapshot.videos.length, 2)
    await js('location.reload()')
    await pause(400)
    await waitFor(() => js('document.querySelectorAll("article").length === 2'))
    assert.equal((await js('window.videosorter.getDatabaseMeta()')).databasePath, path.join(temp, 'videosorter.sqlite'))
  })
  await check('responsive layout fits 960px without horizontal overflow', async () => {
    win.setSize(960, 720)
    await pause(100)
    assert.equal(await js('document.documentElement.scrollWidth <= window.innerWidth'), true)
  })
  await check('local filenames with # load and ArrowRight advances from the current position', async () => {
    await js('document.querySelector("article").children[1].click()')
    await waitFor(() => js('Number.isFinite(document.querySelector(".fixed video")?.duration) && document.querySelector(".fixed video").duration > 30'))
    await js('document.querySelector(".fixed video").pause(); document.querySelector(".fixed video").currentTime = 20')
    await pause(100)
    win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Right' })
    win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Right' })
    await pause(100)
    const time = await js('document.querySelector(".fixed video").currentTime')
    assert.ok(time >= 24.9 && time < 25.2, `Expected 25 seconds, got ${time}`)
  })
  await check('mouse right-click advances five seconds', async () => {
    await js('document.querySelector(".fixed video").dispatchEvent(new MouseEvent("contextmenu", { bubbles: true, cancelable: true, button: 2 }))')
    await pause(100)
    assert.ok(await js('document.querySelector(".fixed video").currentTime >= 29.9'))
  })
  await check('switching video keeps seek controls correct', async () => {
    await js('Array.from(document.querySelectorAll("button")).find(button => button.title === "下一个视频").click()')
    await waitFor(() => js('document.querySelector(".fixed video").readyState >= 2'))
    await js('document.querySelector(".fixed video").pause(); document.querySelector(".fixed video").currentTime = 10')
    win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'Right' })
    win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'Right' })
    await pause(100)
    const time = await js('document.querySelector(".fixed video").currentTime')
    assert.ok(time >= 14.9 && time < 15.2, `Expected 15 seconds, got ${time}`)
    await js('Array.from(document.querySelectorAll("button")).find(button => button.title === "关闭 (Esc)").click()')
  })
  await check('monitor settings modal opens and persists valid configuration', async () => {
    await js('Array.from(document.querySelectorAll("button")).find(button => button.textContent === "目录管理").click()')
    await waitFor(() => js('!!document.querySelector("[role=dialog]") && !Array.from(document.querySelectorAll("button")).find(button => button.textContent.includes("添加目录"))?.disabled'))
    await js('Array.from(document.querySelectorAll("button")).find(button => button.textContent.includes("添加目录")).click()')
    await waitFor(() => js('!!document.querySelector("[aria-label=\\"最小大小 1\\"]")'))
    await js('Array.from(document.querySelectorAll("button")).find(button => button.textContent === "保存检测配置").click()')
    await waitFor(() => js('document.querySelector("[role=status]")?.textContent.includes("已保存")'))
    assert.equal((await js('window.videosorter.getMonitors()')).length, 1)
    win.setSize(1366, 850)
    await pause(100)
    await fs.mkdir('output/playwright', { recursive: true })
    await fs.writeFile('output/playwright/monitor-electron.png', (await win.webContents.capturePage()).toPNG())
    await js('document.querySelector("[title=\\"关闭资源库管理\\"]").click()')
  })
  await check('cleanup preview and rule tools open through the real UI', async () => {
    await js('Array.from(document.querySelectorAll("button")).find(button => button.textContent.includes("检查失效路径")).click()')
    await waitFor(() => js('!!document.querySelector("[role=dialog]")'))
    await waitFor(() => js('!Array.from(document.querySelectorAll("[role=dialog] button")).find(button => button.textContent === "检查失效路径")?.disabled'))
    await js('Array.from(document.querySelectorAll("[role=dialog] button")).find(button => button.textContent === "检查失效路径").click()')
    await waitFor(() => js('document.querySelector("[role=status]")?.textContent.includes("0 条失效路径")'))
    await js('document.querySelector("[title=\\"关闭资源库管理\\"]").click()')
    await js('Array.from(document.querySelectorAll("button")).find(button => button.textContent === "规则分类").click()')
    await waitFor(() => js('!!document.querySelector("[role=dialog]")'))
    await pause(200)
    await fs.writeFile('output/playwright/rules-electron.png', (await win.webContents.capturePage()).toPNG())
    await js('document.querySelector("[title=\\"关闭资源库管理\\"]").click()')
    await fs.writeFile('output/playwright/library-electron.png', (await win.webContents.capturePage()).toPNG())
  })
  await check('automatic cleanup settings save through the UI and remain opt in', async () => {
    assert.equal((await js('window.videosorter.getAutomaticCleanup()')).config.enabled, false)
    await js('Array.from(document.querySelectorAll("button")).find(button => button.textContent.includes("检查失效路径")).click()')
    await waitFor(() => js('!!document.querySelector("[aria-label=\\"启用自动失效清理\\"]") && !document.querySelector("[aria-label=\\"启用自动失效清理\\"]").disabled'))
    await js('document.querySelector("[aria-label=\\"启用自动失效清理\\"]").click()')
    await js('Array.from(document.querySelectorAll("button")).find(button => button.textContent === "保存自动清理设置").click()')
    await waitFor(() => js('document.querySelector("[role=status]")?.textContent.includes("已启用")'))
    assert.equal((await js('window.videosorter.getAutomaticCleanup()')).config.enabled, true)
    await js('Array.from(document.querySelectorAll("button")).find(button => button.textContent === "立即检测一轮").click()')
    await waitFor(() => js('document.querySelector("[role=status]")?.textContent.includes("检测完成")'))
    await pause(250)
    await fs.writeFile('output/playwright/automatic-cleanup-electron.png', (await win.webContents.capturePage()).toPNG())
    await js('document.querySelector("[aria-label=\\"启用自动失效清理\\"]").click()')
    await js('Array.from(document.querySelectorAll("button")).find(button => button.textContent === "保存自动清理设置").click()')
    await waitFor(() => js('document.querySelector("[role=status]")?.textContent.includes("已关闭")'))
    await js('document.querySelector("[title=\\"关闭资源库管理\\"]").click()')
  })
  await check('conditional cleanup combines size and both dates in a preview', async () => {
    await js('Array.from(document.querySelectorAll("button")).find(button => button.textContent === "条件清理").click()')
    await waitFor(() => js('!!document.querySelector("[aria-label=\\"清理最大大小MB\\"]")'))
    await js(`(() => {
      const setter = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set;
      const fields = [['清理最大大小MB', '2'], ['文件修改时间早于（不含）', '2027-01-01T00:00'], ['加入视频库时间早于（不含）', '2027-01-01T00:00'], ['清理关键词', 'seek #1']];
      for (const [label, value] of fields) { const input = document.querySelector('[aria-label="' + label + '"]'); setter.call(input, value); input.dispatchEvent(new Event('input', {bubbles:true})); input.dispatchEvent(new Event('change', {bubbles:true})); }
    })()`)
    await js('Array.from(document.querySelectorAll("button")).find(button => button.textContent === "预览条件匹配结果").click()')
    await waitFor(() => js('document.querySelector("[role=status]")?.textContent.includes("匹配 1 条记录")'))
    assert.equal(await js('document.querySelectorAll("tbody tr").length'), 1)
    assert.ok(await js('document.querySelector("tbody").textContent.includes("seek #1.mp4")'))
    await pause(250)
    await fs.writeFile('output/playwright/conditional-cleanup-electron.png', (await win.webContents.capturePage()).toPNG())
  })
  await check('UI cleanup requires confirmation and keeps the selected video file', async () => {
    await js('Array.from(document.querySelectorAll("button")).find(button => button.textContent === "清理所选 1 条记录").click()')
    assert.ok(await js('document.querySelector("[role=alert]").textContent.includes("视频文件保留")'))
    await js('Array.from(document.querySelectorAll("button")).find(button => button.textContent === "确认备份并移除记录").click()')
    await waitFor(() => js('document.querySelector("[role=status]")?.textContent.includes("已移除 1 条记录")'))
    assert.equal((await js('window.videosorter.getLibrarySnapshot()')).videos.length, 1)
    assert.ok((await fs.stat(path.join(videos, 'seek #1.mp4'))).isFile())
    assert.equal((await js('window.videosorter.rescanDirectory()')).scanSummary.added, 0)
  })
  assert.deepEqual(errors, [], `Renderer errors: ${errors.join('\n')}`)
  console.log(`RESULT: ${count} Electron UI checks passed. Isolated data: ${temp}`)
  app.exit(0)
})().catch(error => { console.error(error); console.error('Renderer:', errors); console.error('Window URL:', win?.webContents.getURL()); app.exit(1) })
