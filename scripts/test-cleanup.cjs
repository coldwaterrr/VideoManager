const { app } = require('electron')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const assert = require('node:assert/strict')
const { pathToFileURL } = require('node:url')
const { buildSync } = require('esbuild')
let passed = 0
async function check(name, action) { await action(); console.log(`PASS ${++passed}: ${name}`) }
app.whenReady().then(async () => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'videomanager-cleanup-'))
  app.setPath('userData', temp)
  buildSync({ stdin: { contents: "export * from './electron/database'; export * from './electron/cleanup'; export * from './electron/monitor';", resolveDir: process.cwd() }, outfile: 'dist-electron/cleanup-test.mjs', bundle: true, format: 'esm', platform: 'node', external: ['electron', 'sql.js'] })
  const db = await import(pathToFileURL(path.resolve('dist-electron/cleanup-test.mjs')).href)
  const root = path.join(temp, 'videos')
  await fs.mkdir(root)
  async function file(name, size, modified = '2024-01-01T00:00:00Z') {
    const target = path.join(root, name)
    const handle = await fs.open(target, 'w'); await handle.truncate(size * 1024 ** 2); await handle.close()
    await fs.utimes(target, new Date(modified), new Date(modified))
    return target
  }
  await file('old-small.mp4', 1)
  await file('old-large.mp4', 8)
  await file('new-small.mp4', 1, '2026-06-01T00:00:00Z')
  await file('early-added.mp4', 2, '2023-01-01T00:00:00Z')
  await db.scanVideosFromDirectory(root)
  const { database: sql } = db.getDatabaseHandle()
  sql.run("UPDATE videos SET created_at = '2026-01-01T00:00:00.000Z'")
  sql.run("UPDATE videos SET created_at = '2024-01-01T00:00:00.000Z' WHERE file_name = 'early-added.mp4'")
  const snapshot = () => db.getLibrarySnapshot()
  const count = async () => (await snapshot()).videos.length
  const id = async name => (await snapshot()).videos.find(video => video.name === name).id
  await check('empty, invalid size/date conditions are rejected', async () => {
    for (const filter of [{}, { minSizeMB: -1 }, { maxSizeMB: NaN }, { minSizeMB: 3, maxSizeMB: 1 }, { modifiedBefore: 'not-a-date' }, { addedAfter: '2026-01-02', addedBefore: '2026-01-01' }]) await assert.rejects(db.previewConditionalCleanup(filter))
    assert.equal(await count(), 4)
  })
  await check('size and both independent timestamps combine with AND', async () => {
    const result = await db.previewConditionalCleanup({ minSizeMB: 1, maxSizeMB: 2, modifiedBefore: '2025-01-01T00:00:00Z', addedAfter: '2025-01-01T00:00:00Z' })
    assert.deepEqual(result.videos.map(video => video.name), ['old-small.mp4'])
    assert.equal(result.videos[0].addedAt, '2026-01-01T00:00:00.000Z')
    assert.equal(await count(), 4)
  })
  await check('date cutoffs are exclusive and lower/size bounds inclusive', async () => {
    assert.deepEqual((await db.previewConditionalCleanup({ modifiedBefore: '2024-01-01T00:00:00Z' })).videos.map(video => video.name), ['early-added.mp4'])
    assert.equal((await db.previewConditionalCleanup({ minSizeMB: 1, maxSizeMB: 1 })).videos.length, 2)
    assert.equal((await db.previewConditionalCleanup({ addedAfter: '2026-01-01T00:00:00Z' })).videos.length, 3)
    assert.deepEqual((await db.previewConditionalCleanup({ addedBefore: '2025-01-01', keyword: 'early-added' })).videos.map(video => video.name), ['early-added.mp4'])
  })
  await check('selected subset is removed, backup is complete, physical files remain', async () => {
    const preview = await db.previewConditionalCleanup({ maxSizeMB: 2 })
    const selected = await id('old-small.mp4')
    await db.applyClassification([{ name: 'Cleanup fixture', videoIds: [selected] }])
    const result = await db.applyConditionalCleanup(preview.previewId, [selected, selected])
    assert.equal(result.deletedCount, 1)
    assert.equal(result.skipped, 0)
    assert.equal(await count(), 3)
    assert.equal((await fs.stat(path.join(root, 'old-small.mp4'))).size, 1024 ** 2)
    assert.equal(sql.exec('SELECT COUNT(*) FROM virtual_folder_videos WHERE video_id = ?', [selected])[0].values[0][0], 0)
    const SQL = await require('sql.js')()
    const backup = new SQL.Database(new Uint8Array(await fs.readFile(result.backupPath)))
    assert.equal(backup.exec('SELECT COUNT(*) FROM videos')[0].values[0][0], 4)
    backup.close()
  })
  await check('record-only cleanup is not immediately undone by scanning', async () => {
    const result = await db.scanVideosFromDirectory(root)
    assert.equal(result.scanSummary.added, 0)
    assert.equal(result.videos.some(video => video.name === 'old-small.mp4'), false)
    await file('old-small.mp4', 1.5, '2026-07-01T00:00:00Z')
    const changed = await db.scanVideosFromDirectory(root)
    assert.equal(changed.scanSummary.added, 1)
  })
  await check('modified records and IDs outside the preview are protected', async () => {
    const preview = await db.previewConditionalCleanup({ minSizeMB: 8 })
    await assert.rejects(db.applyConditionalCleanup(preview.previewId, [await id('new-small.mp4')]))
    await assert.rejects(db.applyConditionalCleanup('expired-or-forged-token', [await id('old-large.mp4')]))
    sql.run('UPDATE videos SET file_size = file_size + 1 WHERE id = ?', [await id('old-large.mp4')])
    const result = await db.applyConditionalCleanup(preview.previewId, [await id('old-large.mp4')])
    assert.equal(result.deletedCount, 0)
    assert.equal(result.skipped, 1)
    assert.equal(await count(), 4)
  })
  await check('backup failure prevents all record removal and permits retry', async () => {
    const preview = await db.previewConditionalCleanup({ keyword: 'early-added' })
    const selected = preview.videos[0].id
    const write = fs.writeFile
    fs.writeFile = async (target, ...args) => { if (String(target).includes('.before-cleanup-')) throw new Error('simulated backup failure'); return write(target, ...args) }
    try { await assert.rejects(db.applyConditionalCleanup(preview.previewId, [selected]), /backup failure/) }
    finally { fs.writeFile = write }
    assert.equal(await count(), 4)
    assert.equal((await db.applyConditionalCleanup(preview.previewId, [selected])).deletedCount, 1)
    assert.ok((await fs.stat(path.join(root, 'early-added.mp4'))).isFile())
  })
  await check('automatic cleanup is disabled by default and validates settings', async () => {
    await fs.unlink(path.join(root, 'new-small.mp4'))
    assert.equal((await db.checkAutomaticCleanup(true)).disabled, true)
    assert.equal(await count(), 3)
    for (const config of [{ enabled: true, intervalMinutes: 0, confirmationChecks: 2 }, { enabled: true, intervalMinutes: 1, confirmationChecks: 0 }]) await assert.rejects(db.saveAutomaticCleanup(config))
    assert.equal((await db.getAutomaticCleanup()).config.enabled, false)
  })
  await check('automatic cleanup waits for repeated confirmations and respects interval', async () => {
    await db.saveAutomaticCleanup({ enabled: true, intervalMinutes: 60, confirmationChecks: 2 })
    const first = await db.checkAutomaticCleanup(true)
    assert.equal(first.deletedCount, 0)
    assert.equal(first.status.pendingCount, 1)
    assert.equal((await db.checkAutomaticCleanup()).due, false)
    const second = await db.checkAutomaticCleanup(true)
    assert.equal(second.deletedCount, 1)
    assert.equal(second.status.pendingCount, 0)
    assert.ok((await fs.stat(second.status.backupPath)).size > 0)
    assert.equal(await count(), 2)
  })
  await check('offline root resets pending history and never triggers deletion', async () => {
    await db.saveLibrarySetting('monitor_directories', [{ directory: root, enabled: false }])
    await fs.unlink(path.join(root, 'old-large.mp4'))
    assert.equal((await db.checkAutomaticCleanup(true)).status.pendingCount, 1)
    await fs.rename(root, root + '-offline')
    const offline = await db.checkAutomaticCleanup(true)
    assert.equal(offline.deletedCount, 0)
    assert.equal(offline.status.pendingCount, 0)
    assert.equal(offline.status.skipped, 2)
    await fs.rename(root + '-offline', root)
    assert.equal((await db.checkAutomaticCleanup(true)).deletedCount, 0)
    assert.equal((await db.checkAutomaticCleanup(true)).deletedCount, 1)
  })
  await check('permission failures are skipped rather than treated as missing', async () => {
    const target = path.join(root, 'old-small.mp4')
    const stat = fs.stat
    fs.stat = async (filePath, ...args) => { if (filePath === target) { const error = new Error('Permission denied'); error.code = 'EACCES'; throw error } return stat(filePath, ...args) }
    try {
      const result = await db.checkAutomaticCleanup(true)
      assert.equal(result.deletedCount, 0)
      assert.equal(result.status.skipped, 1)
      assert.equal(result.status.pendingCount, 0)
    } finally { fs.stat = stat }
    assert.equal(await count(), 1)
  })
  await check('recovered paths survive manual and automatic cleanup', async () => {
    const target = path.join(root, 'old-small.mp4')
    await fs.unlink(target)
    const missing = await db.inspectMissingVideos()
    assert.equal((await db.checkAutomaticCleanup(true)).status.pendingCount, 1)
    await file('old-small.mp4', 1.5, '2026-07-01T00:00:00Z')
    assert.equal((await db.cleanupMissingRecords(missing.missing.map(video => video.id), missing.databasePath)).deletedCount, 0)
    assert.equal((await db.checkAutomaticCleanup(true)).status.pendingCount, 0)
    assert.equal(await count(), 1)
  })
  await check('background monitor tick runs cleanup even with no watched directories', async () => {
    await db.saveMonitors([])
    await db.saveAutomaticCleanup({ enabled: true, intervalMinutes: 1, confirmationChecks: 1 })
    await fs.unlink(path.join(root, 'old-small.mp4'))
    await db.checkMonitors()
    assert.equal(await count(), 0)
    assert.equal((await db.getAutomaticCleanup()).status.lastDeletedCount, 1)
    await db.saveAutomaticCleanup({ enabled: false, intervalMinutes: 60, confirmationChecks: 2 })
  })
  await check('switching libraries invalidates conditional cleanup preview', async () => {
    await file('different-library.mp4', 1)
    await db.scanVideosFromDirectory(root)
    const preview = await db.previewConditionalCleanup({ minSizeMB: 0 })
    const other = path.join(temp, 'other.sqlite')
    await fs.copyFile(db.getCurrentDatabasePath(), other)
    await db.loadDatabaseAtPath(other)
    await assert.rejects(db.applyConditionalCleanup(preview.previewId, [preview.videos[0].id]), /数据库已切换/)
    assert.equal(await count(), 1)
  })
  console.log(`RESULT: ${passed} cleanup checks passed. Isolated data: ${temp}`)
  app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
