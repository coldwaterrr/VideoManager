const { app, ipcMain } = require('electron')
const { buildSync } = require('esbuild')
const { spawn } = require('node:child_process')
const { pathToFileURL } = require('node:url')
const path = require('node:path')
const fs = require('node:fs/promises')
const os = require('node:os')
const assert = require('node:assert/strict')
const pause = ms => new Promise(resolve => setTimeout(resolve, ms))

app.whenReady().then(async () => {
  app.setPath('userData', await fs.mkdtemp(path.join(os.tmpdir(), 'videomanager-mpv-')))
  process.env.APP_ROOT = process.cwd()
  buildSync({ entryPoints: ['electron/mpv.ts'], outfile: 'dist-electron/mpv-test.mjs', bundle: true, format: 'esm', platform: 'node', external: ['electron'] })
  const mpv = await import(pathToFileURL(path.resolve('dist-electron/mpv-test.mjs')).href)
  const handlers = new Map()
  const handle = ipcMain.handle.bind(ipcMain)
  ipcMain.handle = (name, callback) => handlers.set(name, callback)
  let ended = 0
  mpv.setMpvWindowRef({ getBounds: () => ({ x: 0, y: 0, width: 960, height: 720 }), webContents: { send: name => { if (name === 'mpv:ended') ended++ } } })
  // Use the real player, decoder and pipe with no visible window or sound.
  mpv.setupMpvIPC((exe, args, options) => spawn(exe, [...args, '--vo=null', '--ao=null', '--force-window=no'], { ...options, windowsHide: true }))
  ipcMain.handle = handle
  const filePath = path.resolve('output/fixtures/seek #1.mp4')
  let result = await handlers.get('mpv:launch')(null, filePath)
  assert.equal(result.success, true, result.error)
  console.log('PASS 1: MPV launch waits for a responsive IPC pipe')
  for (let i = 0; i < 30; i++) {
    if ((await mpv.sendMpvCommand(['get_property', 'duration'])).data > 30) break
    await pause(100)
  }
  assert.equal((await mpv.sendMpvCommand(['set_property', 'pause', true])).success, true)
  assert.equal((await mpv.sendMpvCommand(['set_property', 'time-pos', 20])).success, true)
  await pause(100)
  assert.equal((await mpv.sendMpvCommand(['seek', 5, 'relative+exact'])).success, true)
  await pause(100)
  const time = (await mpv.sendMpvCommand(['get_property', 'time-pos'])).data
  assert.ok(time >= 24.8 && time < 25.2, `Expected 25 seconds, got ${time}`)
  console.log('PASS 2: MPV relative seek advances from 20 to 25 seconds')
  result = await handlers.get('mpv:launch')(null, filePath)
  assert.equal(result.success, true, result.error)
  await pause(200)
  assert.equal(ended, 0)
  assert.equal((await mpv.sendMpvCommand(['get_property', 'pid'])).success, true)
  console.log('PASS 3: exiting old MPV process does not clear or close its replacement')
  assert.equal((await mpv.sendMpvCommand(['nonexistent-command'])).success, false)
  console.log('PASS 4: MPV command errors are returned to the caller')
  const bindings = await fs.readFile(path.join(app.getPath('userData'), 'videomanager-input.conf'), 'utf8')
  assert.ok(bindings.includes('MBTN_RIGHT seek 5 relative+exact'))
  assert.ok(bindings.includes('RIGHT seek 5 relative+exact'))
  console.log('PASS 5: keyboard and mouse right-click use the same relative seek binding')
  mpv.terminateMpv()
  app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
