// Integration tests use a temporary library and never touch the user's database.
const { app } = require('electron')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const assert = require('node:assert/strict')
const { pathToFileURL } = require('node:url')
const { buildSync } = require('esbuild')
let passed = 0
async function check(name, action) { await action(); console.log(`PASS ${++passed}: ${name}`) }

app.whenReady().then(async () => {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'videomanager-test-'))
  app.setPath('userData', temp)
  const out = path.resolve('dist-electron/library-test.mjs')
  buildSync({ stdin: { contents: "export * from './electron/database'; export * from './electron/monitor';", resolveDir: process.cwd() }, outfile: out, bundle: true, format: 'esm', platform: 'node', external: ['electron', 'sql.js'] })
  const db = await import(pathToFileURL(out).href)
  const root = path.join(temp, 'videos')
  await fs.mkdir(path.join(root, 'nested'), { recursive: true })
  async function file(name, mb, age = 120) {
    const target = path.join(root, name)
    const handle = await fs.open(target, 'w')
    await handle.truncate(mb * 1024 ** 2); await handle.close()
    const time = new Date(Date.now() - age * 1000)
    await fs.utimes(target, time, time)
    return target
  }
  const frog = await file('frog-dance.MP4', 1)
  await file('nested/lesson.webm', 3)
  await file('large.mp4', 10)
  await file('empty.mp4', 0)
  let snapshot
  await check('initialization is shared across concurrent requests', async () => {
    const values = await Promise.all(Array.from({ length: 12 }, () => db.ensureDatabase()))
    assert.ok(values.every(meta => meta.databasePath === values[0].databasePath))
  })
  await check('size bounds, mixed case extensions and recursion', async () => {
    snapshot = await db.scanVideosFromDirectory(root, undefined, { minSizeMB: 1, maxSizeMB: 3, formats: ['.mp4', '.webm'] })
    assert.equal(snapshot.videos.length, 2)
    assert.equal(snapshot.scanSummary.added, 2)
  })
  await check('repeat scan preserves IDs, metadata, duration and classification', async () => {
    const video = snapshot.videos.find(item => item.absolutePath === frog)
    const { database: sql } = db.getDatabaseHandle()
    sql.run('UPDATE videos SET duration_seconds = 120, title = ? WHERE id = ?', ['Demo Frog', video.id])
    await db.toggleVideoFolder(video.id, snapshot.folders[0].id)
    const again = await db.scanVideosFromDirectory(root, undefined, { minSizeMB: 1, maxSizeMB: 3, formats: ['.mp4', '.webm'] })
    assert.equal(again.scanSummary.added, 0)
    assert.equal(again.scanSummary.updated, 0)
    assert.equal(again.scanSummary.unchanged, 2)
    assert.equal(again.videos.find(item => item.id === video.id).durationSeconds, 120)
    assert.deepEqual(again.videos.find(item => item.id === video.id).folderIds, [snapshot.folders[0].id])
  })
  await check('changed file updates once and keeps metadata', async () => {
    await file('frog-dance.MP4', 2)
    const result = await db.scanVideosFromDirectory(root, undefined, { maxSizeMB: 3 })
    assert.equal(result.scanSummary.updated, 1)
    assert.equal(result.videos.find(item => item.absolutePath === frog).title, 'Demo Frog')
    assert.equal(result.videos.find(item => item.absolutePath === frog).durationSeconds, 120)
  })
  await check('unreadable directory and invalid ranges fail without changing library', async () => {
    await assert.rejects(db.scanVideosFromDirectory(root, undefined, { minSizeMB: 3, maxSizeMB: 1 }))
    await assert.rejects(db.scanVideosFromDirectory(root, undefined, { formats: [] }))
    await assert.rejects(db.scanVideosFromDirectory(path.join(temp, 'absent')))
    assert.equal((await db.getLibrarySnapshot()).videos.length, 2)
  })
  await check('scan does not hold a transaction across filesystem operations', async () => {
    const scanning = db.scanVideosFromDirectory(root, undefined, { maxSizeMB: 3 })
    await db.createVirtualFolder('Concurrent category')
    await scanning
  })
  await check('classification is atomic, validates IDs and is idempotent', async () => {
    const id = snapshot.videos[0].id
    await assert.rejects(db.applyClassification([{ name: 'Rollback category', videoIds: [id, 999999] }]))
    assert.ok(!(await db.getLibrarySnapshot()).folders.some(item => item.name === 'Rollback category'))
    await db.applyClassification([{ name: 'Test category', videoIds: [id, id] }])
    await db.applyClassification([{ name: 'Test category', videoIds: [id] }])
    const folder = (await db.getLibrarySnapshot()).folders.find(item => item.name === 'Test category')
    assert.equal(folder.videoCount, 1)
    await db.batchClassify([id], folder.id, 'remove')
    assert.equal((await db.getLibrarySnapshot()).folders.find(item => item.id === folder.id).videoCount, 0)
    await db.renameVirtualFolder(folder.id, 'Renamed category')
    assert.ok((await db.getLibrarySnapshot()).folders.some(item => item.name === 'Renamed category'))
  })
  await check('rules preview is read only and new imports can classify automatically', async () => {
    await db.saveClassificationConfig({ autoOnImport: true, rules: [{ name: 'Lessons', keywords: ['lesson'], target: 'name' }] })
    await file('lesson-new.mp4', 1)
    const result = await db.scanVideosFromDirectory(root, undefined, { maxSizeMB: 3 })
    const lesson = result.videos.find(item => item.name === 'lesson-new.mp4')
    assert.equal(lesson.folderIds.length, 1)
    const count = result.folders.length
    const preview = await db.previewClassificationRules()
    assert.ok(Array.isArray(preview))
    assert.equal((await db.getLibrarySnapshot()).folders.length, count)
  })
  await check('recent writes are deferred and non-recursive scan excludes nested files', async () => {
    await file('still-copying.mp4', 1, 0)
    const result = await db.scanVideosFromDirectory(root, undefined, { maxSizeMB: 3, recursive: false, settleSeconds: 10 })
    assert.equal(result.videos.some(item => item.name === 'still-copying.mp4'), false)
  })
  await check('missing-path cleanup makes a restorable backup and removes relations only', async () => {
    await fs.unlink(frog)
    const inspection = await db.inspectMissingVideos()
    assert.equal(inspection.missing.length, 1)
    assert.equal(inspection.missing[0].absolutePath, frog)
    const before = (await db.getLibrarySnapshot()).videos.length
    const result = await db.removeVideoRecords([inspection.missing[0].id], true)
    assert.equal(result.deletedCount, 1)
    assert.equal(result.snapshot.videos.length, before - 1)
    assert.ok((await fs.stat(result.backupPath)).size > 0)
    const SQL = await require('sql.js')()
    const backup = new SQL.Database(new Uint8Array(await fs.readFile(result.backupPath)))
    assert.equal(Number(backup.exec('SELECT COUNT(*) FROM videos')[0].values[0][0]), before)
    backup.close()
    assert.ok((await fs.stat(path.join(root, 'lesson-new.mp4'))).isFile())
    assert.equal(db.getDatabaseHandle().database.exec('SELECT COUNT(*) FROM virtual_folder_videos WHERE video_id NOT IN (SELECT id FROM videos)')[0].values[0][0], 0)
  })
  await check('offline monitored directory is skipped by cleanup', async () => {
    await db.saveLibrarySetting('monitor_directories', [{ directory: root }])
    await fs.rename(root, root + '-offline')
    const result = await db.inspectMissingVideos()
    assert.equal(result.missing.length, 0)
    assert.ok(result.skipped > 0)
    await fs.rename(root + '-offline', root)
  })
  await check('bad database selection preserves the active library and source file', async () => {
    const before = db.getCurrentDatabasePath()
    const invalid = path.join(temp, 'invalid.sqlite')
    await fs.writeFile(invalid, 'not a sqlite database')
    await assert.rejects(db.loadDatabaseAtPath(invalid))
    await assert.rejects(db.loadDatabaseAtPath(path.join(temp, 'not-found.sqlite')))
    assert.equal(db.getCurrentDatabasePath(), before)
    assert.equal(await fs.readFile(invalid, 'utf8'), 'not a sqlite database')
  })
  await check('concurrent persistence produces a valid complete SQLite file', async () => {
    await Promise.all(Array.from({ length: 12 }, (_, index) => db.saveLibrarySetting(`parallel-${index}`, index)))
    const SQL = await require('sql.js')()
    const saved = new SQL.Database(new Uint8Array(await fs.readFile(db.getCurrentDatabasePath())))
    assert.equal(saved.exec("SELECT COUNT(*) FROM app_meta WHERE key LIKE 'parallel-%'")[0].values[0][0], 12)
    assert.equal(saved.exec('PRAGMA integrity_check')[0].values[0][0], 'ok')
    saved.close()
    assert.equal(db.getDatabaseHandle().database.exec('PRAGMA foreign_keys')[0].values[0][0], 1)
  })
  await check('monitor validates settings, detects stable new files and avoids repeat imports', async () => {
    await assert.rejects(db.saveMonitors([{ id: 'a', directory: root, enabled: true, intervalSeconds: 1 }]))
    await assert.rejects(db.saveMonitors([{ id: 'a', directory: root, enabled: true, intervalSeconds: 60, formats: [] }]))
    await assert.rejects(db.saveMonitors([{ id: 'a', directory: root, enabled: true, intervalSeconds: 60 }, { id: 'b', directory: root, enabled: true, intervalSeconds: 60 }]))
    await db.saveMonitors([{ id: 'root', directory: root, enabled: true, intervalSeconds: 60, minSizeMB: 1, maxSizeMB: 3, formats: ['.mp4', '.webm'], recursive: true, settleSeconds: 10 }])
    assert.equal((await db.getMonitors()).length, 1)
    await file('lesson-monitor.mp4', 1)
    await fs.utimes(path.join(root, 'still-copying.mp4'), new Date(), new Date())
    const first = await db.checkMonitors(true)
    assert.equal(first.added, 1)
    const second = await db.checkMonitors(true)
    assert.equal(second.added, 0)
    assert.equal(second.updated, 0)
    const deferred = (await db.getLibrarySnapshot()).videos.find(item => item.name === 'still-copying.mp4')
    assert.equal(deferred, undefined)
    await db.saveMonitors([{ id: 'root', directory: root, enabled: false, intervalSeconds: 60 }])
    await file('disabled.mp4', 1)
    assert.equal((await db.checkMonitors(true)).added, 0)
  })
  await check('player seek bounds and filename encoding', async () => {
    buildSync({ entryPoints: ['src/lib/playback.ts'], outfile: path.resolve('dist-electron/playback-test.cjs'), format: 'cjs', platform: 'node' })
    const { seekTarget, localFileUrl } = require('../dist-electron/playback-test.cjs')
    assert.equal(seekTarget(30, 120, 5), 35)
    assert.equal(seekTarget(30, 0, 5), null)
    assert.equal(seekTarget(3, 120, -5), 0)
    assert.equal(seekTarget(118, 120, 5), 119.95)
    assert.equal(localFileUrl('E:\\videos\\a #1%?.mp4'), 'file:///E:/videos/a%20%231%25%3F.mp4')
  })
  console.log(`RESULT: ${passed} integration checks passed. Temporary library: ${temp}`)
  app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
