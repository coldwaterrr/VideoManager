// Rasterize the checked-in vector, then package standard Windows icon sizes.
const { app, BrowserWindow } = require('electron')
const fs = require('node:fs/promises')
const path = require('node:path')

app.whenReady().then(async () => {
  const source = await fs.readFile(path.resolve('public/videomanager.svg'), 'utf8')
  const window = new BrowserWindow({ show: false, webPreferences: { sandbox: true } })
  await window.loadURL('data:text/html,<meta charset="utf-8">')
  const sizes = [16, 20, 24, 32, 40, 48, 64, 128, 256]
  const images = await window.webContents.executeJavaScript(`(async () => {
    const image = new Image()
    image.src = 'data:image/svg+xml;base64,' + ${JSON.stringify(Buffer.from(source).toString('base64'))}
    await image.decode()
    return ${JSON.stringify(sizes)}.map(size => {
      const canvas = document.createElement('canvas')
      canvas.width = canvas.height = size
      canvas.getContext('2d').drawImage(image, 0, 0, size, size)
      return canvas.toDataURL('image/png').split(',')[1]
    })
  })()`)
  const frames = images.map(image => Buffer.from(image, 'base64'))
  const header = Buffer.alloc(6 + sizes.length * 16)
  header.writeUInt16LE(1, 2)
  header.writeUInt16LE(sizes.length, 4)
  let offset = header.length
  frames.forEach((frame, index) => {
    const entry = 6 + index * 16
    header[entry] = header[entry + 1] = sizes[index] === 256 ? 0 : sizes[index]
    header.writeUInt16LE(1, entry + 4)
    header.writeUInt16LE(32, entry + 6)
    header.writeUInt32LE(frame.length, entry + 8)
    header.writeUInt32LE(offset, entry + 12)
    offset += frame.length
  })
  await fs.writeFile('public/videomanager.ico', Buffer.concat([header, ...frames]))
  await fs.writeFile('public/videomanager.png', frames.at(-1))
  await fs.writeFile('public/videomanager-tray.png', frames[sizes.indexOf(32)])
  await fs.writeFile('electron/icon-fallback.ts', `// Generated by scripts/generate-icons.cjs from public/videomanager.svg.\nexport const fallbackIcon = 'data:image/png;base64,${images[sizes.indexOf(32)]}'\n`)
  console.log(`Generated PNG, tray PNG, and ICO with ${sizes.join('/')}px frames`)
  window.destroy()
  app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
